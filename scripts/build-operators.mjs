// Downloads Arknights operator data (zh_CN) and writes a compact JS dataset
// used by the sorter web app. Run: node sorter/scripts/build-operators.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(__dirname, '..', 'data');

const CHAR_TABLE =
  'https://raw.githubusercontent.com/Kengxxiao/ArknightsGameData/master/zh_CN/gamedata/excel/character_table.json';

// Avatar / portrait CDN (jsDelivr mirror of the GitHub resource repo for reliability + CORS)
const AVATAR_BASE =
  'https://cdn.jsdelivr.net/gh/yuanyan3060/ArknightsGameResource@main/avatar';
const PORTRAIT_BASE =
  'https://cdn.jsdelivr.net/gh/yuanyan3060/ArknightsGameResource@main/portrait';

const RARITY_MAP = {
  TIER_1: 1, TIER_2: 2, TIER_3: 3, TIER_4: 4, TIER_5: 5, TIER_6: 6,
};

// Some older dumps use numeric rarity (0-5) instead of TIER_x
function normRarity(r) {
  if (typeof r === 'number') return r + 1;
  if (RARITY_MAP[r]) return RARITY_MAP[r];
  return 0;
}

const PROFESSIONS = new Set([
  'PIONEER', 'WARRIOR', 'TANK', 'SNIPER', 'CASTER', 'MEDIC', 'SUPPORT', 'SPECIAL',
]);

const PRTS_API = 'https://prts.wiki/api.php';
const ART_WIDTH = 512; // 结果页立绘缩略图宽度

// 批量向 PRTS 查询「立绘_<名>_1.png」的缩略图直链，返回 name -> url
async function fetchArtUrls(names) {
  const out = new Map();
  const norm = (n) => '文件:立绘 ' + n + ' 1.png'; // MediaWiki 规范化后的标题
  for (let i = 0; i < names.length; i += 50) {
    const batch = names.slice(i, i + 50);
    const titles = batch.map((n) => 'File:立绘_' + n + '_1.png').join('|');
    const url =
      PRTS_API + '?action=query&format=json&prop=imageinfo&iiprop=url' +
      '&iiurlwidth=' + ART_WIDTH + '&titles=' + encodeURIComponent(titles);
    let pages = {};
    try {
      const r = await fetch(url, { headers: { 'User-Agent': 'ak-sorter-build/1.0' } });
      pages = (await r.json()).query?.pages || {};
    } catch (e) {
      console.warn('  PRTS batch failed:', e.message);
    }
    const byTitle = {};
    for (const k in pages) byTitle[pages[k].title] = pages[k];
    for (const n of batch) {
      const p = byTitle[norm(n)];
      const ii = p && p.imageinfo && p.imageinfo[0];
      if (ii) out.set(n, ii.thumburl || ii.url);
    }
    process.stdout.write('\r  PRTS art: ' + Math.min(i + 50, names.length) + '/' + names.length);
  }
  process.stdout.write('\n');
  return out;
}

async function main() {
  console.log('Downloading character_table.json ...');
  const res = await fetch(CHAR_TABLE);
  if (!res.ok) throw new Error('download failed: ' + res.status);
  const data = await res.json();

  const ops = [];
  for (const [id, c] of Object.entries(data)) {
    if (!id.startsWith('char_')) continue;
    if (!PROFESSIONS.has(c.profession)) continue; // drop tokens / traps
    if (c.isNotObtainable) continue; // drop unreleased / non-standard
    const rarity = normRarity(c.rarity);
    if (!rarity) continue;
    ops.push({
      id,
      name: c.name,
      en: c.appellation || '',
      rarity,
      cls: c.profession,
      nation: c.nationId || '',
    });
  }

  // Sort: rarity desc, then original sortIndex-ish by id for stability
  ops.sort((a, b) => b.rarity - a.rarity || a.id.localeCompare(b.id));

  // 从 PRTS 拉取全身立绘直链（结果页领奖台/大图用）
  console.log('Fetching PRTS art URLs ...');
  const artMap = await fetchArtUrls(ops.map((o) => o.name));
  let artHit = 0;
  for (const o of ops) {
    const u = artMap.get(o.name);
    if (u) { o.art = u; artHit++; }
  }
  console.log('PRTS art matched:', artHit, '/', ops.length);

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const payload = { avatarBase: AVATAR_BASE, portraitBase: PORTRAIT_BASE, operators: ops };
  const js =
    '// Auto-generated by scripts/build-operators.mjs. Do not edit by hand.\n' +
    'window.ARK_DATA = ' + JSON.stringify(payload) + ';\n';
  fs.writeFileSync(path.join(OUT_DIR, 'operators.js'), js);
  fs.writeFileSync(
    path.join(OUT_DIR, 'operators.json'),
    JSON.stringify(payload, null, 0)
  );

  const byRarity = {};
  for (const o of ops) byRarity[o.rarity] = (byRarity[o.rarity] || 0) + 1;
  const byNation = {};
  for (const o of ops) byNation[o.nation || '(none)'] = (byNation[o.nation || '(none)'] || 0) + 1;
  console.log('Wrote', ops.length, 'operators');
  console.log('By rarity:', byRarity);
  console.log('By nation:', JSON.stringify(byNation, null, 0));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
