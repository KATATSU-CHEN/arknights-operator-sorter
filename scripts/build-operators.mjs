// Downloads Arknights operator data (zh_CN) and writes a compact JS dataset
// used by the sorter web app. Run: node sorter/scripts/build-operators.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(__dirname, '..', 'data');

const CHAR_TABLE =
  'https://raw.githubusercontent.com/Kengxxiao/ArknightsGameData/master/zh_CN/gamedata/excel/character_table.json';

// Avatar CDN (jsDelivr mirror of the GitHub resource repo for reliability + CORS)
const AVATAR_BASE =
  'https://cdn.jsdelivr.net/gh/yuanyan3060/ArknightsGameResource@main/avatar';

const RARITY_MAP = {
  TIER_1: 1, TIER_2: 2, TIER_3: 3, TIER_4: 4, TIER_5: 5, TIER_6: 6,
};

// Some older dumps use numeric rarity (0-5) instead of TIER_x
function normRarity(r) {
  if (typeof r === 'number') return r + 1;
  if (RARITY_MAP[r]) return RARITY_MAP[r];
  return 0;
}

const PROFESSIONS = new Set([
  'PIONEER', 'WARRIOR', 'TANK', 'SNIPER', 'CASTER', 'MEDIC', 'SUPPORT', 'SPECIAL',
]);

async function main() {
  console.log('Downloading character_table.json ...');
  const res = await fetch(CHAR_TABLE);
  if (!res.ok) throw new Error('download failed: ' + res.status);
  const data = await res.json();

  const ops = [];
  for (const [id, c] of Object.entries(data)) {
    if (!id.startsWith('char_')) continue;
    if (!PROFESSIONS.has(c.profession)) continue; // drop tokens / traps
    if (c.isNotObtainable) continue; // drop unreleased / non-standard
    const rarity = normRarity(c.rarity);
    if (!rarity) continue;
    ops.push({
      id,
      name: c.name,
      en: c.appellation || '',
      rarity,
      cls: c.profession,
    });
  }

  // Sort: rarity desc, then original sortIndex-ish by id for stability
  ops.sort((a, b) => b.rarity - a.rarity || a.id.localeCompare(b.id));

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const payload = { avatarBase: AVATAR_BASE, operators: ops };
  const js =
    '// Auto-generated by scripts/build-operators.mjs. Do not edit by hand.\n' +
    'window.ARK_DATA = ' + JSON.stringify(payload) + ';\n';
  fs.writeFileSync(path.join(OUT_DIR, 'operators.js'), js);
  fs.writeFileSync(
    path.join(OUT_DIR, 'operators.json'),
    JSON.stringify(payload, null, 0)
  );

  const byRarity = {};
  for (const o of ops) byRarity[o.rarity] = (byRarity[o.rarity] || 0) + 1;
  console.log('Wrote', ops.length, 'operators');
  console.log('By rarity:', byRarity);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
